"""Regenerate characters.js from tools/characters.source.json.

Usage: python3 tools/build_data.py

Each character in the source file looks like:
  {
    "name": ["Harry", "Potter"],          # name parts; wrap an alias in parens, e.g. "(Tom Riddle)"
    "house": "Gryffindor",                 # or "Slytherin", "None", "Beauxbatons", ...
    "book": 1,                             # first book they appear in, 1-7
    "blood": ["Human", "Half-blood"],      # species, then blood status (status optional)
    "affiliation": ["Order of the Phoenix", "Dumbledore's Army"],
    "family": ["Potter"],                  # surnames/families they belong to
    "patronus": "Stag"                     # optional; only canon Patronuses, shown when you win
  }
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = json.loads((root / "tools" / "characters.source.json").read_text())
keep = ["name", "house", "book", "blood", "affiliation", "family"]
out, names = [], set()
for i, c in enumerate(src):
    missing = [k for k in ["name", "house", "book", "blood"] if k not in c]
    if missing:
        sys.exit(f"entry {i} ({c.get('name')}) is missing {missing}")
    if not (1 <= c["book"] <= 7):
        sys.exit(f"{' '.join(c['name'])}: book must be 1-7")
    key = " ".join(c["name"]).lower()
    if key in names:
        sys.exit(f"duplicate character: {key}")
    names.add(key)
    entry = {k: c.get(k, []) for k in keep}
    if c.get("patronus"):
        entry["patronus"] = c["patronus"]
    out.append(entry)
js = "// Generated by tools/build_data.py — edit tools/characters.source.json instead.\nwindow.CHARACTERS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "characters.js").write_text(js)
print(f"wrote {len(out)} characters")
